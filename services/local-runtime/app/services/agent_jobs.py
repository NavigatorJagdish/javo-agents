"""Durable bounded execution of explicitly supported local read operations.

Other specialist prototypes are not dispatched. The persisted authorization
snapshot is generated by the owner API, not accepted from a job's input fields.
"""

from __future__ import annotations

import asyncio
from contextlib import suppress
from datetime import datetime, timezone
import logging
import time
from typing import Literal
from uuid import uuid4

from fastapi import HTTPException
from pydantic import BaseModel, ConfigDict, Field, ValidationError
from sqlalchemy import func, select, text, update
from sqlalchemy.engine import make_url

from app import database as db
from app.config import get_settings
from app.core.resource_manager import get_resource_manager
from app.core.runtime_lease import RuntimeLease
from app.models.agent import AgentDefinition, AgentExecution, AgentStatus, ExecutionStatus
from app.models.security import AuditAction, AuditLog
from app.models.task import Task, TaskState

logger = logging.getLogger(__name__)
SUPPORTED_ACTIONS = {
    "budget_guardian": ["summary", "check_budget"],
    "goal_persistence": ["summary"],
}
PERMISSIONS = {
    "budget_guardian": ["read_usage", "enforce_budget"],
    "goal_persistence": ["read_goals"],
}


class BudgetInput(BaseModel):
    model_config = ConfigDict(extra="forbid")
    action: Literal["summary", "check_budget"] = "summary"
    provider: Literal["ollama", "gemini", "openai"] = "ollama"


class GoalInput(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)
    action: Literal["summary"] = "summary"
    goal_id: str = Field(min_length=1, max_length=36)


def validate_job(agent_key: str, payload: dict) -> dict:
    if agent_key not in SUPPORTED_ACTIONS:
        raise HTTPException(501, "This specialist does not yet have a verified execution path")
    schema = GoalInput if agent_key == "goal_persistence" else BudgetInput
    try:
        return schema.model_validate(payload).model_dump()
    except ValidationError:
        raise HTTPException(422, "Invalid fields for this supported specialist operation") from None


def trail(task: Task, action: str, details: dict | None = None):
    task.audit_trail = [
        *(task.audit_trail or []),
        {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "action": action,
            "actor": "local-owner",
            "details": details or {},
        },
    ]


async def enqueue(session, agent: AgentDefinition, payload: dict, task_id: str | None = None):
    """Caller holds a SQLite immediate transaction, bounding concurrent admission."""
    normalized = validate_job(agent.agent_key, payload)
    if not agent.is_enabled:
        raise HTTPException(409, "Agent is disabled")
    manager = get_resource_manager()
    if manager._emergency_stopped:
        raise HTTPException(409, "Runtime is emergency stopped; explicitly resume first")
    count = await session.scalar(
        select(func.count())
        .select_from(AgentExecution)
        .where(AgentExecution.status.in_([ExecutionStatus.QUEUED, ExecutionStatus.RUNNING]))
    )
    if count >= get_settings().max_queue_size:
        raise HTTPException(429, "Saved execution queue is full")
    if normalized.get("goal_id"):
        from app.api.routes.goals import _get_goal_or_404

        await _get_goal_or_404(normalized["goal_id"], session)
    task = None
    if task_id:
        task = await session.get(Task, task_id)
        if task is None:
            raise HTTPException(404, "Task not found")
        if task.assigned_agent and task.assigned_agent != agent.agent_key:
            raise HTTPException(409, "Task belongs to a different specialist")
        if task.permissions is not None and not all(
            task.permissions.get(p) is True for p in PERMISSIONS[agent.agent_key]
        ):
            raise HTTPException(403, "Task does not grant the required read permissions")
        active = await session.scalar(
            select(AgentExecution.id)
            .where(
                AgentExecution.task_id == task_id,
                AgentExecution.status.in_([ExecutionStatus.QUEUED, ExecutionStatus.RUNNING]),
            )
            .limit(1)
        )
        if active:
            raise HTTPException(409, "Task already has a queued or running execution")
        if task.deadline and task.deadline.replace(tzinfo=timezone.utc) <= datetime.now(
            timezone.utc
        ):
            raise HTTPException(409, "Task deadline has passed; review before executing")
    execution = AgentExecution(
        id=str(uuid4()),
        agent_id=agent.id,
        task_id=task_id,
        created_at=datetime.now(timezone.utc),
        status=ExecutionStatus.QUEUED,
        inputs={
            "payload": normalized,
            "authorization": {
                "owner": "local-owner",
                "permissions": PERMISSIONS[agent.agent_key],
                "version": 1,
            },
        },
    )
    session.add(execution)
    if task:
        task.assigned_agent = agent.agent_key
        task.state = TaskState.PENDING
        task.completed_at = None
        trail(task, "execution_queued", {"execution_id": execution.id, "agent": agent.agent_key})
    session.add(
        AuditLog(
            action=AuditAction.EXECUTE,
            resource_type="agent_execution",
            resource_id=execution.id,
            description="Owner queued a supported local read operation",
            details={"agent": agent.agent_key, "permissions": PERMISSIONS[agent.agent_key]},
        )
    )
    await session.commit()
    await session.refresh(execution)
    return execution


async def cancel_execution(session, execution: AgentExecution, *, commit=True):
    changed = await session.execute(
        update(AgentExecution)
        .where(
            AgentExecution.id == execution.id,
            AgentExecution.status.in_([ExecutionStatus.QUEUED, ExecutionStatus.RUNNING]),
        )
        .values(
            status=ExecutionStatus.CANCELLED,
            completed_at=datetime.now(timezone.utc),
            error="Cancelled by owner",
        )
    )
    if changed.rowcount != 1:
        raise HTTPException(409, "Execution is already finished; reload its result")
    if execution.task_id:
        task = await session.get(Task, execution.task_id)
        if task:
            task.state = TaskState.CANCELLED
            trail(task, "execution_cancelled", {"execution_id": execution.id})
    session.add(
        AuditLog(
            action=AuditAction.UPDATE,
            resource_type="agent_execution",
            resource_id=execution.id,
            description="Owner cancelled a supported specialist execution",
        )
    )
    if commit:
        await session.commit()
    agent_worker.cancel(execution.id)


class AgentJobWorker:
    def __init__(self):
        self._task = None
        self._operation = None
        self._active_id = None
        self._closing = False
        self._lease = None

    async def start(self):
        if self._task is not None:
            return
        self._closing = False
        database_path = make_url(get_settings().database_url).database
        if database_path and database_path != ":memory:":
            self._lease = RuntimeLease(database_path + ".agent-worker.lock")
            self._lease.acquire()
        # A process crash never means success or permits blind replay.
        async with db.async_session_factory() as session:
            interrupted = list(
                (
                    await session.execute(
                        select(AgentExecution).where(
                            AgentExecution.status == ExecutionStatus.RUNNING
                        )
                    )
                )
                .scalars()
                .all()
            )
            for execution in interrupted:
                execution.status = ExecutionStatus.FAILED
                execution.error = (
                    "Runtime restarted during execution; review and explicitly run again"
                )
                execution.completed_at = datetime.now(timezone.utc)
                if execution.task_id:
                    task = await session.get(Task, execution.task_id)
                    if task and task.state == TaskState.RUNNING:
                        task.state = TaskState.FAILED
                        trail(task, "execution_interrupted", {"execution_id": execution.id})
            await session.execute(
                update(AgentDefinition)
                .where(
                    AgentDefinition.status == AgentStatus.RUNNING,
                )
                .values(status=AgentStatus.IDLE)
            )
            await session.commit()
        self._task = asyncio.create_task(self._run(), name="javo-supported-agent-jobs")

    async def _claim(self):
        async with db.async_session_factory() as session:
            await session.execute(text("BEGIN IMMEDIATE"))
            execution = (
                await session.execute(
                    select(AgentExecution)
                    .where(AgentExecution.status == ExecutionStatus.QUEUED)
                    .order_by(AgentExecution.created_at, AgentExecution.id)
                    .limit(1)
                )
            ).scalar_one_or_none()
            if execution is None:
                await session.commit()
                return None
            agent = await session.get(AgentDefinition, execution.agent_id)
            content = execution.inputs if isinstance(execution.inputs, dict) else {}
            authorization = content.get("authorization", {})
            if (
                agent is None
                or not agent.is_enabled
                or agent.agent_key not in SUPPORTED_ACTIONS
                or authorization
                != {
                    "owner": "local-owner",
                    "permissions": PERMISSIONS.get(agent.agent_key),
                    "version": 1,
                }
            ):
                await self._reject_claim(
                    session,
                    execution,
                    "Unsupported, disabled or legacy unreviewed execution; submit a supported operation",
                )
                return None
            try:
                payload = validate_job(agent.agent_key, content.get("payload", {}))
            except HTTPException:
                await self._reject_claim(
                    session,
                    execution,
                    "Saved operation fields are invalid; submit a new supported request",
                )
                return None
            task = await session.get(Task, execution.task_id) if execution.task_id else None
            if execution.task_id and task is None:
                await self._reject_claim(
                    session, execution, "Linked task is unavailable; review before running again"
                )
                return None
            if task and task.state == TaskState.CANCELLED:
                execution.status = ExecutionStatus.CANCELLED
                execution.error = "Linked task was cancelled"
                execution.completed_at = datetime.now(timezone.utc)
                await session.commit()
                return None
            if task and task.state != TaskState.PENDING:
                await self._reject_claim(
                    session, execution, "Linked task is not pending; review before running again"
                )
                return None
            if task and (
                (
                    task.permissions is not None
                    and not all(
                        task.permissions.get(p) is True for p in PERMISSIONS[agent.agent_key]
                    )
                )
                or (
                    task.deadline
                    and task.deadline.replace(tzinfo=timezone.utc) <= datetime.now(timezone.utc)
                )
            ):
                await self._reject_claim(
                    session,
                    execution,
                    "Task permissions or deadline no longer allow execution; review before rerunning",
                )
                return None
            # Check controls again inside the claim transaction.
            manager = get_resource_manager()
            if manager._paused or manager._emergency_stopped:
                await session.commit()
                return None
            execution.status = ExecutionStatus.RUNNING
            execution.started_at = datetime.now(timezone.utc)
            agent.status = AgentStatus.RUNNING
            if task:
                task.state = TaskState.RUNNING
                trail(task, "execution_started", {"execution_id": execution.id})
            await session.commit()
            return execution.id, agent.id, agent.agent_key, payload

    async def _reject_claim(self, session, execution, reason):
        execution.status, execution.error = ExecutionStatus.FAILED, reason
        execution.completed_at = datetime.now(timezone.utc)
        task = await session.get(Task, execution.task_id) if execution.task_id else None
        if task and task.state in {TaskState.PENDING, TaskState.RUNNING}:
            task.state = TaskState.FAILED
            trail(task, "execution_failed", {"execution_id": execution.id})
        await session.commit()

    async def _invoke(self, agent_key, payload):
        async with db.async_session_factory() as session:
            enabled = await session.scalar(
                select(AgentDefinition.is_enabled).where(AgentDefinition.agent_key == agent_key)
            )
        if not enabled or get_resource_manager()._emergency_stopped:
            raise RuntimeError("Agent was disabled or execution stopped")
        if agent_key == "budget_guardian":
            from app.agents.budget_guardian import BudgetGuardianAgent

            agent = BudgetGuardianAgent()
        elif agent_key == "goal_persistence":
            from app.agents.goal_persistence import GoalPersistenceAgent

            agent = GoalPersistenceAgent()
        else:
            raise RuntimeError("Unsupported specialist")
        return await agent.execute(payload)

    async def _finish(self, execution_id, agent_id, state, result=None, error=None, duration=None):
        async with db.async_session_factory() as session:
            execution = await session.get(AgentExecution, execution_id)
            if execution and execution.status == ExecutionStatus.RUNNING:
                # Never overwrite an owner/emergency cancellation with success.
                changed = await session.execute(
                    update(AgentExecution)
                    .where(
                        AgentExecution.id == execution_id,
                        AgentExecution.status == ExecutionStatus.RUNNING,
                    )
                    .values(
                        status=state,
                        outputs=result,
                        error=error,
                        completed_at=datetime.now(timezone.utc),
                        duration_ms=duration,
                    )
                )
                if changed.rowcount == 1 and execution.task_id:
                    task = await session.get(Task, execution.task_id)
                    if task and task.state == TaskState.RUNNING:
                        task.state = {
                            ExecutionStatus.COMPLETED: TaskState.COMPLETED,
                            ExecutionStatus.CANCELLED: TaskState.CANCELLED,
                        }.get(state, TaskState.FAILED)
                        task.outputs = result
                        task.completed_at = datetime.now(timezone.utc)
                        trail(task, "execution_" + state.value, {"execution_id": execution_id})
                if changed.rowcount == 1:
                    session.add(
                        AuditLog(
                            action=AuditAction.EXECUTE,
                            resource_type="agent_execution",
                            resource_id=execution_id,
                            description="Supported specialist execution " + state.value,
                        )
                    )
            agent = await session.get(AgentDefinition, agent_id)
            if agent:
                agent.status = AgentStatus.IDLE if agent.is_enabled else AgentStatus.DISABLED
            await session.commit()

    async def _one(self, claim):
        execution_id, agent_id, key, payload = claim
        self._active_id = execution_id
        start = time.perf_counter()
        try:
            self._operation = asyncio.create_task(
                get_resource_manager().submit_task(
                    "agent-job-" + execution_id, lambda: self._invoke(key, payload)
                )
            )
            result = await asyncio.wait_for(self._operation, timeout=30)
            if result.get("status") != "success":
                raise RuntimeError("Specialist did not confirm success")
            await self._finish(
                execution_id,
                agent_id,
                ExecutionStatus.COMPLETED,
                result=result,
                duration=int((time.perf_counter() - start) * 1000),
            )
        except asyncio.CancelledError:
            await self._finish(
                execution_id,
                agent_id,
                ExecutionStatus.CANCELLED,
                error="Execution cancelled or runtime shutting down",
            )
            if self._closing:
                raise
        except Exception:
            await self._finish(
                execution_id,
                agent_id,
                ExecutionStatus.FAILED,
                error="Execution failed or was interrupted; inspect runtime controls and saved inputs",
            )
        finally:
            self._operation = None
            self._active_id = None

    async def _run(self):
        while True:
            try:
                manager = get_resource_manager()
                if manager.can_accept_work()[0]:
                    claim = await self._claim()
                    if claim:
                        await self._one(claim)
            except asyncio.CancelledError:
                raise
            except Exception:
                logger.error("Saved specialist dispatch failed; no success is assumed")
            await asyncio.sleep(0.25)

    def cancel(self, execution_id):
        if self._active_id == execution_id and self._operation is not None:
            self._operation.cancel()

    async def stop(self):
        self._closing = True
        try:
            if self._task is not None:
                self._task.cancel()
                with suppress(asyncio.CancelledError):
                    await self._task
                self._task = None
        finally:
            self._task = None
            if self._lease is not None:
                self._lease.release()
                self._lease = None


agent_worker = AgentJobWorker()
